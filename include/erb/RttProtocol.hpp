constexpr std::uint32_t RttProtocol::fourcc (const char str_0 [5])
{
   return
        std::uint32_t (str_0 [3]) << 24
      | std::uint32_t (str_0 [2]) << 16
      | std::uint32_t (str_0 [1]) << 8
      | std::uint32_t (str_0 [0]) << 0;
}



