#include <utility>



namespace erb
{
namespace rig
{



/*
==============================================================================
Name : ctor
==============================================================================
*/

Connection::Connection (std::function <void ()> release)
:  _release (std::move (release))
{
}



/*
==============================================================================
Name : ctor
==============================================================================
*/

Connection::Connection (Connection && rhs)
:  _release (std::exchange (rhs._release, nullptr))
{
}



/*
==============================================================================
Name : dtor
==============================================================================
*/

Connection::~Connection ()
{
   if (_release)
   {
      _release ();
   }
}



}  // namespace rig
}  // namespace erb



