/*\\\ PUBLIC \\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\\*/

/*
==============================================================================
Name : ctor
Note :
   State is only the bytes.
==============================================================================
*/

SdCard::SdCard (const SdCard & rhs)
:  _bytes (rhs._bytes)
{
}



/*
==============================================================================
Name : ctor
==============================================================================
*/

SdCard::SdCard (SdCard && rhs)
:  _bytes (std::move (rhs._bytes))
{
}



/*
==============================================================================
Name : operator =
==============================================================================
*/

SdCard &  SdCard::operator = (const SdCard & rhs)
{
   _bytes = rhs._bytes;

   return *this;
}



/*
==============================================================================
Name : operator =
==============================================================================
*/

SdCard &  SdCard::operator = (SdCard && rhs)
{
   _bytes = std::move (rhs._bytes);

   return *this;
}



/*
==============================================================================
Name : empty
==============================================================================
*/

bool  SdCard::empty () const
{
   return _bytes.empty ();
}



/*
==============================================================================
Name : size
==============================================================================
*/

std::size_t SdCard::size () const
{
   return _bytes.size ();
}



